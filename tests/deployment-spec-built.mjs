import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {spawnSync} from 'node:child_process';
import {makeHarness} from './recovery-harness.mjs';

fs.mkdirSync('.build/deployment-20261015/qa',{recursive:true});
const out='.build/deployment-20261015/spec-built-test.html';
const build=spawnSync(process.execPath,['scripts/build-deployment.mjs','--out',out,'--icons','src/assets/nav-icons.json'],{encoding:'utf8'});
assert.equal(build.status,0,build.stderr||build.stdout);
const html=fs.readFileSync(out,'utf8'),script=html.match(/<script>([\s\S]*)<\/script>/)?.[1];
assert(script,'Generated HTML script exists');
const blankSeed={version:'0.11.0',storageRevision:0,currentProjectId:'',selectedProjectId:'',projects:[],entities:[],auditEvents:[],notifications:[],companies:[],lawCatalog:[],lawChanges:[],lawUpdateRuns:[],projectLawImpacts:[],migrationConflicts:[],integrityIssues:[],storageQuarantine:[],sourceLoad:{status:'unavailable',schemaVersion:'notion-development-projects-v1',expectedCount:null,actualCount:0,hasMore:null,syncedAt:''}};
const {context,nodes}=makeHarness({modules:[],seed:blankSeed});
vm.runInContext(script,context,{filename:path.resolve(out)});
const A=vm.runInContext('App',context);
const auth=A.spec.productionContracts.authentication;
assert.equal(auth.allowedEmailDomain,'igisam.com','Final product loads current exact email-domain policy');
assert.equal(auth.codeLength,6,'Final product loads six-digit email-verification policy');
assert.equal(auth.commonInitialCode,false,'Initial shared code is superseded');
assert.equal(auth.passwordRequired,false,'No unrequested password enforcement');
assert.equal(auth.implemented,false,'Unconfigured email flow is not claimed implemented');
assert(A.spec.legacyReferences.authenticationPolicies.length>0,'Historical authentication policies preserved');
A.go('spec','overview');
assert(nodes.get('content').innerHTML.includes('보호된 검증 미리보기'));
assert(!nodes.get('content').innerHTML.includes('운영 범위</td><td>로컬 HTML'));
A.go('spec','functions');
assert(nodes.get('content').innerHTML.includes('6자리'));
assert(!nodes.get('content').innerHTML.includes('전 직원 공통 첫 이용 코드'));
assert.equal(A.state.projects.length,0);
assert.equal(A.state.sourceLoad.status,'unavailable');
console.log(JSON.stringify({suite:'deployment-spec-built',passed:1,failed:0,actualGeneratedProductExecuted:true,sourceRequired:false,actualBrowser:false}));
