import assert from 'node:assert/strict';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const {outputFiles} = await build({entryPoints:['src/components/system/WorkFeedText.jsx'],bundle:true,write:false,format:'esm',platform:'node'});
const {default: Text} = await import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`);
const render = text => renderToStaticMarkup(React.createElement(Text,{text,mentions:[{label:'양준모'},{label:'CM'}]}));
const html = render('**확인 @양준모** (https://example.com/a?q=1&x=2).\n@CM https://example.com/wiki/(test)');
assert.match(html,/<strong/);
assert.match(html,/data-feed-mention/);
assert.match(html,/href="https:\/\/example.com\/a\?q=1&amp;x=2"/);
assert.match(html,/href="https:\/\/example.com\/wiki\/\(test\)"/);
assert.equal((html.match(/<a /g)||[]).length,2);
assert.match(html,/target="_blank" rel="noopener noreferrer"/);
assert.equal(render('https://.'), 'https://.');
assert.ok(!render('javascript:alert(1) data:text/html,test https://').includes('<a '));
assert.ok(!render('<script>alert(1)</script>').includes('<script>'));
assert.match(render('**https://example.com**'),/<strong[^>]*><a /);
assert.equal((render('https://example.com/@CM').match(/<a /g)||[]).length,1);
console.log('PASS: URL query strings, trailing punctuation, balanced brackets, bold and mentions, safe protocols and escaped HTML');
